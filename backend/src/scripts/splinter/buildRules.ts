// Writes rules.ts from the .sql files beside it: each Supabase advisor rule as
// the statement securityChecks.ts sends, its first line (`create view ... as`)
// removed, held in a constant so evalQueryTypes' census can read and describe
// it like every other statement. securityChecks.test.ts fails if rules.ts and
// the files differ.
//   npx tsx src/scripts/splinter/buildRules.ts
import fs from "node:fs";
import { fileURLToPath } from "node:url";
import { RULE_FILES, ruleStatement } from "./ruleText.js";

const here = (name: string) => fileURLToPath(new URL(`./${name}`, import.meta.url));

// A template literal's text: a backslash, a backtick and `${` are the three
// things that would not read back as themselves.
const literal = (text: string) => "`" + text.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${") + "`";

const constants = RULE_FILES.map(({ file, constant }) => {
  const statement = ruleStatement(file, fs.readFileSync(here(file), "utf8"));
  return `/** ${file}, less its first line. */\nexport const ${constant} = ${literal(statement)};\n`;
});

fs.writeFileSync(
  here("rules.ts"),
  "// Generated by buildRules.ts from the .sql files beside it. Do not edit: fetch\n" +
    "// the files again from splinter and rerun it (README.md).\n\n" +
    constants.join("\n"),
);
console.log(`rules.ts: ${RULE_FILES.map((r) => r.constant).join(", ")}`);
